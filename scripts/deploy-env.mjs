// npm run deploy:env
//
// Writes the exact environment for each host into deploy/out/ (git-ignored):
//   render.env           paste into Render > studycrm-api > Environment > "Add from .env"
//   vercel-crm.env       paste into Vercel > admin project > Settings > Environment Variables (paste the whole file)
//   vercel-portal.env    same, portal project
//   vercel-partner.env   same, partner project
// The website needs no variables.
// Only live values are copied. ENABLE_DEV_ROUTES and every LOCAL_ value are left out on purpose.
import fs from 'node:fs';
import path from 'node:path';
import { readEnv, SERVICES, ROOT } from './envfiles.mjs';

const OUT = path.join(ROOT, 'deploy', 'out');
fs.mkdirSync(OUT, { recursive: true });

const names = { render: 'render.env', crm: 'vercel-crm.env', portal: 'vercel-portal.env', partner: 'vercel-partner.env' };
let missing = 0;
for (const [id, svc] of Object.entries(SERVICES)) {
  if (!svc.file) { console.log(`- ${svc.title}: no variables needed`); continue; }
  const env = readEnv(svc.file) || {};
  const lines = [`# ${svc.title}`, `# generated by npm run deploy:env on ${new Date().toISOString().slice(0, 10)}`];
  for (const [k, v] of Object.entries(svc.fixed)) lines.push(`${k}=${v}`);
  for (const k of svc.keys) {
    if (!env[k]) { missing++; lines.push(`# MISSING: ${k}=`); continue; }
    lines.push(`${k}=${env[k]}`);
  }
  for (const k of svc.optional ?? []) if (env[k]) lines.push(`${k}=${env[k]}`);
  const file = path.join(OUT, names[id]);
  fs.writeFileSync(file, lines.join('\n') + '\n', { mode: 0o600 });
  console.log(`- ${svc.title}: deploy/out/${names[id]}${svc.secret ? '  (contains secrets: never commit or share)' : ''}`);
}
console.log(missing ? `\n${missing} value(s) missing, marked "# MISSING" in the files. Run npm run doctor.` : '\nDone. Paste each file into its host, then push to main.');
