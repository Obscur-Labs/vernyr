import { PDFDocument, StandardFonts, rgb, type PDFFont, type PDFPage } from 'pdf-lib';

/** A simple business document (receipts): header, from / to, key-value lines, a table and totals (legacy/server/docpdf.js). */
const W = (s: unknown) => String(s ?? '').replace(/₹/g, 'Rs.').replace(/[“”]/g, '"').replace(/[‘’]/g, "'").replace(/[–—]/g, '-').replace(/[^\x20-\x7E\n]/g, '');
function wrap(text: unknown, font: PDFFont, size: number, maxW: number) {
  const out: string[] = [];
  for (const para of W(text).split('\n')) {
    let line = '';
    for (const word of para.split(/\s+/)) { const t = line ? line + ' ' + word : word; if (font.widthOfTextAtSize(t, size) > maxW && line) { out.push(line); line = word; } else line = t; }
    out.push(line);
  }
  return out;
}
export const fmt = (n: unknown, c?: string) => `${(Math.round(Number(n || 0) * 100) / 100).toLocaleString('en-IN', { minimumFractionDigits: 2, maximumFractionDigits: 2 })} ${c || ''}`.trim();

export async function docPdf(o: { title: string; badge?: string; from?: string[]; to?: string[]; kv?: [string, string][]; columns?: [string, number][]; rows?: string[][]; totals?: [string, string][]; note?: string }) {
  const doc = await PDFDocument.create();
  const font = await doc.embedFont(StandardFonts.Helvetica), bold = await doc.embedFont(StandardFonts.HelveticaBold);
  const PW = 595.28, PH = 841.89, M = 40;
  let page!: PDFPage, y = 0;
  const t = (s: unknown, x: number, yy: number, op: { size?: number; bold?: boolean; color?: ReturnType<typeof rgb> } = {}) =>
    page.drawText(W(s), { x, y: yy, size: op.size || 9, font: op.bold ? bold : font, color: op.color || rgb(0.12, 0.12, 0.12) });
  const header = () => {
    page = doc.addPage([PW, PH]);
    page.drawRectangle({ x: 0, y: PH - 62, width: PW, height: 62, color: rgb(0.06, 0.12, 0.23) });
    t('La Europa Education', M, PH - 30, { size: 18, bold: true, color: rgb(1, 1, 1) });
    t('Euroverse Service LLP', M, PH - 46, { size: 9, color: rgb(0.85, 0.85, 0.85) });
    t(o.badge || o.title, PW - M - bold.widthOfTextAtSize(W(o.badge || o.title), 15), PH - 36, { size: 15, bold: true, color: rgb(0.79, 0.64, 0.15) });
    y = PH - 90;
  };
  header();
  t(o.title, M, y, { size: 13, bold: true }); y -= 22;
  const colY = y;
  if (o.from) { t('From', M, y, { bold: true }); o.from.filter(Boolean).forEach((l, i) => t(l, M, y - 13 - i * 11, { size: 8.5 })); }
  if (o.to) { t('To', 310, colY, { bold: true }); o.to.filter(Boolean).forEach((l, i) => t(l, 310, colY - 13 - i * 11, { size: 8.5 })); }
  y -= 13 + Math.max((o.from ?? []).length, (o.to ?? []).length) * 11 + 14;
  (o.kv ?? []).forEach(([k, v], i) => { t(k, M, y - i * 13, { bold: true, size: 8.5 }); t(v, M + 130, y - i * 13, { size: 8.5 }); });
  y -= (o.kv ?? []).length * 13 + 14;
  const cols = o.columns ?? [];
  const head = () => { page.drawRectangle({ x: M, y: y - 4, width: PW - 2 * M, height: 16, color: rgb(0.93, 0.94, 0.97) }); let x = M; for (const [c, w] of cols) { t(c, x + 2, y, { bold: true, size: 7.5 }); x += w; } y -= 16; };
  if (cols.length) head();
  for (const r of o.rows ?? []) {
    const cells = r.map((v, i) => wrap(v, font, 7.5, cols[i][1] - 4));
    const h = Math.max(...cells.map((c) => c.length)) * 9.5 + 4;
    if (y - h < 90) { header(); head(); }
    let x = M;
    cells.forEach((lines, i) => { lines.forEach((w, k) => t(w, x + 2, y - k * 9.5, { size: 7.5 })); x += cols[i][1]; });
    y -= h;
    page.drawLine({ start: { x: M, y: y + 6 }, end: { x: PW - M, y: y + 6 }, thickness: 0.3, color: rgb(0.85, 0.85, 0.85) });
  }
  if (cols.length && !(o.rows ?? []).length) { t('No lines.', M, y, { size: 9 }); y -= 14; }
  y -= 8;
  if (y < 140) header();
  (o.totals ?? []).forEach(([k, v], i, a) => { const last = i === a.length - 1; t(k, 340, y - i * 14, { bold: last }); t(v, 460, y - i * 14, { bold: last }); });
  y -= (o.totals ?? []).length * 14 + 18;
  if (o.note) wrap(o.note, font, 8.5, PW - 2 * M).forEach((w, k) => t(w, M, y - k * 11, { size: 8.5 }));
  const pages = doc.getPages();
  pages.forEach((p, i) => p.drawText(W(`Generated by the La Europa CRM | Page ${i + 1} of ${pages.length}`), { x: M, y: 20, size: 7, font, color: rgb(0.5, 0.5, 0.5) }));
  return Buffer.from(await doc.save());
}
